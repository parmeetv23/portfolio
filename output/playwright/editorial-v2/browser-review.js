async (page) => {
  const errors = [], warnings = [], failedResponses = [], checks = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if(m.type() === 'error') errors.push(m.text()); if(m.type() === 'warning') warnings.push(m.text()); });
  page.on('response', r => { if(r.status() >= 400) failedResponses.push({status:r.status(),url:r.url()}); });
  const check = (name, pass) => { checks.push({name,pass}); if(!pass) throw new Error(name); };
  const settle = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await page.setViewportSize({width:1440,height:1000});
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.reload();
  await page.evaluate(async () => { await document.fonts.ready; });
  await settle();
  const importButton = page.getByRole('button', {name:'Resume import', exact:true});
  await importButton.click();
  check('Import study updates its pressed state', await page.getByRole('button',{name:'Reset study',exact:true}).getAttribute('aria-pressed') === 'true');
  await page.locator('.v2-import-figure').screenshot({path:'output/playwright/editorial-v2/import-resumed.png'});
  await page.keyboard.press('Space');
  check('Space resets the focused import study', await importButton.getAttribute('aria-pressed') === 'false');
  await page.getByRole('button',{name:'Parse',exact:true}).focus();
  await page.keyboard.press('Enter');
  check('Enter opens Parse', await page.locator('#v2-stage-0').isVisible());
  await page.getByRole('button',{name:'Generate',exact:true}).click();
  check('Generate replaces Parse', await page.locator('#v2-stage-2').isVisible() && !(await page.locator('#v2-stage-0').isVisible()));
  await page.locator('.v2-compiler-study').screenshot({path:'output/playwright/editorial-v2/compiler-generate.png'});
  await page.keyboard.press('Space');
  check('Space collapses the open compiler panel', !(await page.locator('#v2-stage-2').isVisible()));
  await page.getByRole('button',{name:'Resolve',exact:true}).click();
  const next = page.getByRole('button',{name:'Next implementation note'});
  await next.click();
  check('Notes advance to stable-key upserts', await page.getByRole('heading',{name:'Stable-key upserts',exact:true}).isVisible());
  await page.keyboard.press('Enter');
  check('Notes advance with Enter', await page.getByRole('heading',{name:'Transactional imports',exact:true}).isVisible());
  await next.click();
  check('Notes wrap to the first item', await page.getByRole('heading',{name:'Persistent checkpoints',exact:true}).isVisible());
  await page.getByRole('button',{name:'Previous implementation note'}).click();
  check('Notes wrap backwards', await page.getByRole('heading',{name:'Transactional imports',exact:true}).isVisible());
  await next.click();
  await page.evaluate(() => { const section=document.querySelector('.v2-practice'); window.scrollTo({top:section.getBoundingClientRect().top+scrollY+50,behavior:'instant'}); });
  await settle();
  const pinA=await page.locator('.v2-practice-heading').boundingBox();
  await page.evaluate(() => window.scrollBy({top:120,behavior:'instant'}));
  await settle();
  const pinB=await page.locator('.v2-practice-heading').boundingBox();
  check('Desktop experience heading stays pinned during reading', Math.abs(pinA.y-pinB.y) < 2);
  const opacity=await page.locator('.v2-reading span').evaluateAll(nodes=>nodes.map(n=>getComputedStyle(n).opacity));
  check('Reading passage reaches full opacity', opacity.every(x=>x==='1'));
  await page.screenshot({path:'output/playwright/editorial-v2/desktop-experience.png'});
  await page.evaluate(() => window.scrollTo({top:0,behavior:'instant'}));
  await page.screenshot({path:'output/playwright/editorial-v2/desktop.png'});
  await page.screenshot({path:'output/playwright/editorial-v2/desktop-full.png',fullPage:true});
  await page.setViewportSize({width:768,height:1024});
  await settle();
  await page.screenshot({path:'output/playwright/editorial-v2/tablet.png'});
  await page.screenshot({path:'output/playwright/editorial-v2/tablet-full.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await settle();
  await page.screenshot({path:'output/playwright/editorial-v2/mobile.png'});
  await page.screenshot({path:'output/playwright/editorial-v2/mobile-full.png',fullPage:true});
  await page.getByRole('button',{name:'Scroll more projects'}).click();
  await page.waitForFunction(() => document.querySelector('.v2-strip-track').scrollLeft > 0);
  check('Project strip scrolls on request', await page.locator('.v2-strip-track').evaluate(el=>el.scrollLeft > 0));
  await page.locator('.v2-strip-track a').last().focus();
  check('Clipped project links can be reached by keyboard', await page.locator('.v2-strip-track a').last().evaluate(el=>el===document.activeElement));
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.setViewportSize({width:1440,height:1000});
  await page.reload();
  await settle();
  check('Reduced motion removes pinning', await page.locator('.pin-spacer').count()===0);
  check('Reduced motion keeps the reading passage visible', await page.locator('.v2-reading span').evaluateAll(nodes=>nodes.every(n=>getComputedStyle(n).opacity==='1')));
  check('Reduced motion disables illustration transitions', await page.locator('.v2-checkpoint-plane').evaluate(el=>getComputedStyle(el).transitionDuration==='0s'));
  await page.keyboard.press('Tab');
  check('Skip link is first in keyboard order', await page.locator('.lab-skip').evaluate(el=>el===document.activeElement));
  check('Keyboard focus has a visible outline', await page.locator('.lab-skip').evaluate(el=>getComputedStyle(el).outlineStyle!=='none'));
  await page.keyboard.press('Enter');
  check('Skip link targets main content', await page.evaluate(()=>location.hash==='#v2-main'));
  const paths=await page.locator('a[href^="/"]').evaluateAll(nodes=>[...new Set(nodes.map(n=>n.getAttribute('href').split('#')[0]))]);
  const linkResponses=[];
  for(const path of paths) { const response=await page.request.get('http://127.0.0.1:3000'+path); linkResponses.push({path,status:response.status()}); }
  check('All local navigation destinations respond successfully', linkResponses.every(r=>r.status===200));
  const browser=page.context().browser();
  const staticContext=await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:844}});
  const staticPage=await staticContext.newPage();
  await staticPage.goto('http://127.0.0.1:3000/design-lab/editorial-v2');
  check('Core portfolio content renders without JavaScript', await staticPage.locator('h1').isVisible() && await staticPage.locator('.v2-reading').isVisible() && await staticPage.locator('table').count()===1);
  await staticContext.close();
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.goto('http://127.0.0.1:3000/design-lab/editorial-v2');
  await settle();
  return {checks, errors, warnings, failedResponses, linkResponses};
}
